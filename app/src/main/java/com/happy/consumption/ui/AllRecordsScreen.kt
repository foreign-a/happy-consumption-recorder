@Composable
fun AllRecordsScreen(model: AllRecordsViewModel, username: String, auth: AppViewModel,
    language: LanguageSettings? = null, backup: BackupViewModel? = null,
    listState: androidx.compose.foundation.lazy.LazyListState = rememberLazyListState(), schedule: PersonalSchedule? = null) {
    val data by model.state.collectAsState()
    val item by model.selectedRecord.collectAsState()
    val inline by model.inline.collectAsState()
    val selected by model.selectedDate.collectAsState()
    val busy by model.busy.collectAsState()
    val jumping by model.jumping.collectAsState()
    val message by model.message.collectAsState()
    val leavePrompt by model.leavePrompt.collectAsState()
    val dialog by model.dialog.collectAsState()
    val batch by model.batchDelete.collectAsState()
    val generated by model.generatedCount.collectAsState()
    var more by remember { mutableStateOf(false) }
    val regions = remember { mutableMapOf<String, Rect>() }
    var adding by remember { mutableStateOf(false) }
    val lifecycle = androidx.lifecycle.compose.LocalLifecycleOwner.current.lifecycle
    var opening by remember { mutableIntStateOf(0) }
    DisposableEffect(lifecycle) {
        val observer = androidx.lifecycle.LifecycleEventObserver { _, event ->
            if (event == androidx.lifecycle.Lifecycle.Event.ON_START) opening++
        }
        lifecycle.addObserver(observer)
        onDispose { lifecycle.removeObserver(observer) }
    }
    LaunchedEffect(item, inline == null, opening, jumping, busy, dialog, batch != null) {
        val current = item
        if (current != null && inline == null && !jumping && !busy && dialog == ConfirmationState.Idle && batch == null && current.date == selected) model.editAmount(current,
            if (current.date == model.dates.today().toString())
                (schedule?.read() ?: MealSchedule()).suggested(java.time.Instant.now()) else Meal.BREAKFAST, clearMessage = false)
    }
    BackHandler(inline?.changed == true) { model.leave() }
    Scaffold(bottomBar = { PhoneKeypad(model, inline, Modifier.fillMaxWidth()) }) { padding ->
        Column(Modifier.fillMaxSize().padding(padding).verticalScroll(rememberScrollState())
            .padding(horizontal = 20.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
            DateCalendar(model, false, regions)
            Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically) {
                Text(selected, style = MaterialTheme.typography.titleLarge, fontWeight = FontWeight.Bold)
                Row {
                    TextButton(onClick = { model.jumpToDate(model.dates.today().toString()) }) { Text(stringResource(R.string.today)) }
                    Box {
                        TextButton(onClick = { more = true }, modifier = Modifier.testTag("record_actions")) { Text("⋯") }
                        DropdownMenu(expanded = more, onDismissRequest = { more = false }) {
                            DropdownMenuItem(text = { Text(stringResource(R.string.generate_history)) }, onClick = {
                                more = false; model.leave { model.generatePastThirtyDays() }
                            }, enabled = !busy)
                            DropdownMenuItem(text = { Text(stringResource(R.string.delete)) }, onClick = {
                                more = false; model.openBatchDelete()
                            }, enabled = !busy && !data.error, modifier = Modifier.testTag("batch_delete_entry"))
                        }
                    }
                }
            }
            if (generated != null) Text(stringResource(R.string.history_generated, generated!!))
            if (message != null) Text(stringResource(message!!), color = if (message == R.string.batch_deleted) MaterialTheme.colorScheme.primary else MaterialTheme.colorScheme.error)
            if (data.error) {
                Text(stringResource(R.string.storage_error))
                TextButton(onClick = model::retry) { Text(stringResource(R.string.retry)) }
            } else if (item != null) {
                RecordCard(item!!, inline, { model.editAmount(item!!, it) }, model::saveInline,
                    { model.requestDelete(item!!) }, !busy, regions, true)
            } else if (data.loading) LinearProgressIndicator(Modifier.fillMaxWidth())
            else Text(stringResource(R.string.empty_records))
            TextButton(onClick = { model.leave { adding = true } }, enabled = !busy) { Text(stringResource(R.string.add_past_record)) }
        }
    }
    if (adding) AddRecordDialog(model) { adding = false }
    RecordDialogs(model)
    BatchDeleteDialog(model)
    if (leavePrompt) AlertDialog(onDismissRequest = model::keepEditing,
        title = { Text(stringResource(R.string.unsaved_title)) }, text = { Text(stringResource(R.string.unsaved_message)) },
        confirmButton = { TextButton(onClick = model::saveInline, enabled = !busy, modifier = Modifier.testTag("leave_save")) { Text(stringResource(R.string.confirm_save)) } },
        dismissButton = { Row {
            TextButton(onClick = model::discardInline, enabled = !busy, modifier = Modifier.testTag("leave_discard")) { Text(stringResource(R.string.discard_changes)) }
            TextButton(onClick = model::keepEditing, enabled = !busy, modifier = Modifier.testTag("leave_keep")) { Text(stringResource(R.string.keep_editing)) }
        } })
}

@Composable
fun RecordCard(item: ConsumptionItem, draft: InlineDraft?, onAmount: (Meal) -> Unit,
    onConfirm: () -> Unit, onDelete: () -> Unit, enabled: Boolean, regions: MutableMap<String, Rect>, selected: Boolean = false) {
    Column(Modifier.fillMaxWidth().testTag("record_${item.id}"), verticalArrangement = Arrangement.spacedBy(4.dp)) {
        Text(item.totals(), style = MaterialTheme.typography.headlineMedium, fontWeight = FontWeight.Bold,
            modifier = Modifier.testTag("total_${item.id}"))
        for (pair in Meal.entries.chunked(2)) Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            for (meal in pair) TextButton(onClick = { onAmount(meal) }, enabled = enabled,
                colors = ButtonDefaults.textButtonColors(containerColor =
                    if (draft?.selected == meal) MaterialTheme.colorScheme.primaryContainer else Color.Transparent),
                modifier = Modifier.weight(1f).testTag("amount_${item.id}_${meal.name}")) {
                Column(horizontalAlignment = Alignment.CenterHorizontally) {
                    Text(stringResource(mealLabel(meal)), style = MaterialTheme.typography.labelMedium)
                    Text(draft?.preview(meal) ?: item.currencies[meal].format(item.value(meal)),
                        style = MaterialTheme.typography.titleLarge)
                }
            }
        }
        HorizontalDivider()
    }
}
